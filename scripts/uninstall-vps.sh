die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

log() {
  printf '\033[1;34m==>\033[0m %s\n' "$*" >&2
}

warn() {
  printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2
}

trim_space() {
  local value=$1
  value="${value#"${value%%[![:space:]]*}"}"
  value="${value%"${value##*[![:space:]]}"}"
  printf '%s' "$value"
}

tolower_one() {
  trim_space "$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')"
}

have_tty_stdio() {
  [[ -t 0 && -t 1 ]]
}

prompt_line_or_default() {
  local prompt=$1 default=$2 value
  if [[ -n "$default" ]]; then
    printf '%s [%s]: ' "$prompt" "$default" >&2
  else
    printf '%s: ' "$prompt" >&2
  fi
  IFS= read -r value || die "input cancelled"
  value="$(trim_space "$value")"
  [[ -n "$value" ]] || value=$default
  printf '%s' "$value"
}

prompt_line_nonempty() {
  local prompt=$1 value
  while true; do
    value="$(prompt_line_or_default "$prompt" "")"
    [[ -n "$value" ]] && break
    warn "this value is required"
  done
  printf '%s' "$value"
}

prompt_yes_no() {
  local prompt=$1 default=$2 suffix value lc
  lc="$(tolower_one "$default")"
  case "$lc" in
    y|yes) suffix='[Y/n]' ;;
    n|no) suffix='[y/N]' ;;
    *) suffix='[y/n]' ;;
  esac

  while true; do
    printf '%s %s ' "$prompt" "$suffix" >&2
    IFS= read -r value || die "input cancelled"
    value="$(trim_space "$value")"
    [[ -n "$value" ]] || value=$default
    lc="$(tolower_one "$value")"
    case "$lc" in
      y|yes) return 0 ;;
      n|no) return 1 ;;
      *) warn "answer yes or no" ;;
    esac
  done
}

