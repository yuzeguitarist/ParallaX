confirm_or_exit() {
  [[ "$YES" == "1" || "$DRY_RUN" == "1" ]] && return 0
  [[ "$NON_INTERACTIVE" != "1" ]] || die "--non-interactive needs --yes or --dry-run"
  have_tty_stdio || die "confirmation needs an interactive terminal; pass --yes only if you are sure"

  local answer
  printf '\nType UNINSTALL to continue: ' >&2
  IFS= read -r answer || die "confirmation cancelled"
  [[ "$answer" == "UNINSTALL" ]] || die "confirmation did not match; nothing changed"
}

remote_uninstall() {
  local q_sudo q_remote_bin q_remote_config q_service_name q_remove_bbr q_remove_parca q_remove_ufw q_remove_user
  q_sudo="$(shell_quote "$REMOTE_SUDO")"
  q_remote_bin="$(shell_quote "$REMOTE_BIN")"
  q_remote_config="$(shell_quote "$REMOTE_CONFIG")"
  q_service_name="$(shell_quote "$SERVICE_NAME")"
  q_remove_bbr="$(shell_quote "$REMOVE_BBR")"
  q_remove_parca="$(shell_quote "$REMOVE_PARCA_AGENT")"
  q_remove_ufw="$(shell_quote "$REMOVE_UFW_RULE")"
  q_remove_user="$(shell_quote "$REMOVE_USER")"

  local remote_script
  # Literal printf keeps payload bytes opaque on Bash 3.2 and avoids macOS
  # heredoc prefill stalls when the system lowers new pipes to 512 bytes.
  # shellcheck disable=SC2016
  printf -v remote_script '%s' 'set -Eeuo pipefail
export PATH="$PATH:/usr/sbin:/sbin"

: "${SUDO:=}"
: "${REMOTE_BIN:?missing REMOTE_BIN}"
: "${REMOTE_CONFIG:?missing REMOTE_CONFIG}"
: "${SERVICE_NAME:?missing SERVICE_NAME}"
: "${REMOVE_BBR:=1}"
: "${REMOVE_PARCA_AGENT:=0}"
: "${REMOVE_UFW_RULE:=1}"
: "${REMOVE_USER:=0}"

if [[ -n "$SUDO" ]] && ! command -v "$SUDO" >/dev/null 2>&1; then
  echo "$SUDO was requested but is not installed on the VPS" >&2
  exit 1
fi

SERVICE_UNIT="$SERVICE_NAME.service"
SERVICE_PATH="/etc/systemd/system/$SERVICE_UNIT"
PARCA_SERVICE="parca-agent.service"
PARCA_SERVICE_PATH="/etc/systemd/system/$PARCA_SERVICE"

run_root() {
  if [[ -n "$SUDO" ]]; then
    "$SUDO" "$@"
  else
    "$@"
  fi
}

remove_file() {
  local path=$1
  if [[ -e "$path" || -L "$path" ]]; then
    run_root rm -f -- "$path"
    echo "removed $path"
  else
    echo "missing $path"
  fi
}

remove_dir_tree() {
  local path=$1
  if [[ -d "$path" && ! -L "$path" ]]; then
    run_root rm -rf -- "$path"
    echo "removed $path"
  else
    echo "missing $path"
  fi
}

remove_dir_if_empty() {
  local path=$1
  if [[ -d "$path" && ! -L "$path" ]]; then
    run_root rmdir "$path" >/dev/null 2>&1 || true
  fi
}

stop_disable_unit() {
  local unit=$1 path=$2 exists=0 unit_files loaded
  [[ -e "$path" || -L "$path" ]] && exists=1
  if command -v systemctl >/dev/null 2>&1; then
    if ! unit_files="$(systemctl list-unit-files --no-legend "$unit")" ||
      ! loaded="$(systemctl list-units --all --no-legend "$unit")"; then
      echo "could not inspect $unit; aborting uninstall before removing its files" >&2
      return 1
    fi
    if [[ -n "$unit_files" || -n "$loaded" ]]; then
      exists=1
    fi
    if [[ "$exists" == "1" ]]; then
      if ! run_root systemctl stop "$unit"; then
        echo "could not stop $unit; aborting uninstall before removing its files" >&2
        return 1
      fi
      run_root systemctl disable "$unit" || true
      run_root systemctl reset-failed "$unit" || true
    fi
  elif [[ "$exists" == "1" ]]; then
    echo "systemctl not found; cannot safely stop $unit, aborting uninstall" >&2
    return 1
  fi
}

remove_parallax_service() {
  stop_disable_unit "$SERVICE_UNIT" "$SERVICE_PATH"
  remove_file "$SERVICE_PATH"
}

decode_service_executable() {
  local command=$1 token="" quote="" char i
  SERVICE_EXECUTABLE=""
  # Inspect only the first argv token. Escapes/specifiers can disguise the
  # executable name, so an undecodable token cannot establish non-ownership.
  for ((i=0; i<${#command}; i++)); do
    char=${command:i:1}
    case "$char" in
      (\\|'\''$'\''|'\''%'\''|'\''`'\''|'\''*'\''|'\''?'\''|'\''['\''|'\'']'\'') return 1 ;;
      ('\''"'\''|"'\''")
        if [[ "$quote" == "$char" ]]; then
          quote=""
        elif [[ -z "$quote" ]]; then
          quote=$char
        else
          return 1
        fi
        ;;
      ([[:space:]])
        if [[ -n "$quote" ]]; then token+=$char; else break; fi
        ;;
      (*) token+=$char ;;
    esac
  done
  [[ -z "$quote" ]] || return 1
  # systemd unquotes the first word before extracting its command prefixes.
  while [[ -n "$token" ]]; do
    case "${token:0:1}" in
      ('\''-'\''|'\''@'\''|'\'':'\''|'\''+'\''|'\''!'\''|'\''|'\'') token=${token:1} ;;
      (*) break ;;
    esac
  done
  [[ -n "$token" ]] || return 1
  [[ "$token" != */* || "$token" == /* ]] || return 1
  SERVICE_EXECUTABLE=$token
}

uses_parallax_resources() {
  local settings=$1 line command
  local parallax_word="(^|[[:space:]/\"'\''])(plx|parallax)([[:space:];\"'\'']|$)"
  if grep -Eq '\''^[[:space:]]*(User[[:space:]]*=[[:space:]]*parallax([[:space:]]|$)|Description[[:space:]]*=[[:space:]]*ParallaX|StateDirectory[[:space:]]*=[[:space:]]*parallax([[:space:]]|$)|WorkingDirectory[[:space:]]*=[[:space:]]*/var/lib/parallax([[:space:]]|$))'\'' < <(printf '\''%s\n'\'' "$settings") ||
    grep -Fq -- "$REMOTE_BIN" < <(printf '\''%s\n'\'' "$settings") ||
    grep -Fq -- "$REMOTE_CONFIG" < <(printf '\''%s\n'\'' "$settings"); then
    return 0
  fi
  while IFS= read -r line; do
    [[ "$line" =~ ^[[:space:]]*ExecStart[[:space:]]*= ]] || continue
    command=${line#*=}
    command=${command#"${command%%[![:space:]]*}"}
    [[ -n "$command" ]] || continue
    if [[ "$command" == \{* ]]; then
      if [[ "$command" != *'\''path='\''* ]]; then
        INSPECTION_COMPLETE=0
        echo "kept instance files: could not inspect service executable" >&2
        return 0
      fi
      command=${command#*'\''path='\''}
    fi
    if ! decode_service_executable "$command"; then
      INSPECTION_COMPLETE=0
      echo "kept instance files: could not inspect service executable" >&2
      return 0
    fi
    case "${SERVICE_EXECUTABLE##*/}" in (plx|parallax) return 0 ;; esac
    # Keep recognizing explicit wrappers that mention a ParallaX command;
    # their argument inspection can still conservatively reject shell syntax.
    grep -Eq "$parallax_word" < <(printf '\''%s\n'\'' "$command") && return 0
  done < <(printf '\''%s\n'\'' "$settings")
  return 1
}

OTHER_INSTANCES=0
INSPECTION_COMPLETE=1
OTHER_SETTINGS=""
OTHER_PATHS=""

decode_config_args() {
  local command=$1 token="" quote="" char started=0 i arg config found=0
  local args=()
  # Decode quoted argv without eval or shell expansion. Escapes and variable /
  # specifier expansion require systemd'\''s parser, so preserve files instead.
  for ((i=0; i<${#command}; i++)); do
    char=${command:i:1}
    case "$char" in
      (\\|'\''$'\''|'\''%'\'') return 1 ;;
      ('\''"'\''|"'\''")
        if [[ "$quote" == "$char" ]]; then
          quote=""
        elif [[ -z "$quote" ]]; then
          quote=$char
        else
          token+=$char
        fi
        started=1
        ;;
      ([[:space:]])
        if [[ -n "$quote" ]]; then
          token+=$char
        elif [[ "$started" == "1" ]]; then
          args+=("$token")
          token=""
          started=0
        fi
        ;;
      (*) token+=$char; started=1 ;;
    esac
  done
  [[ -z "$quote" ]] || return 1
  [[ "$started" == "0" ]] || args+=("$token")
  for ((i=0; i<${#args[@]}; i++)); do
    arg=${args[i]}
    case "$arg" in
      (-c|--config)
        (( i+1 < ${#args[@]} )) || return 1
        i=$((i+1))
        config=${args[i]}
        ;;
      (--config=*) config=${arg#--config=} ;;
      (-c/*) config=${arg#-c} ;;
      (--) break ;;
      (*) continue ;;
    esac
    [[ "$found" == "0" && "$config" == /* && "$config" != *[[:space:]]* &&
      "$config" != *'\''$'\''* && "$config" != *'\''%'\''* ]] || return 1
    DECODED_CONFIGS+=("$config")
    found=1
  done
  [[ "$found" == "1" ]]
}

decode_settings_configs() {
  local settings=$1 line command found=0
  DECODED_CONFIGS=()
  while IFS= read -r line; do
    [[ "$line" =~ ^[[:space:]]*ExecStart[[:space:]]*= ]] || continue
    command=${line#*=}
    command=${command#"${command%%[![:space:]]*}"}
    [[ -n "$command" ]] || continue
    if [[ "$command" == \{* ]]; then
      # systemctl show serializes ExecStart with a path + argv[] wrapper.
      [[ "$command" == *'\''argv[]='\''* ]] || return 1
      command=${command#*'\''argv[]='\''}
      [[ "$command" != *'\''argv[]='\''* && "$command" == *'\'' ;'\''* ]] || return 1
      command=${command%%'\'' ;'\''*}
    fi
    decode_config_args "$command" || return 1
    found=1
  done < <(printf '\''%s\n'\'' "$settings")
  [[ "$found" == "1" ]]
}

decode_config_references() {
  # This is a bounded inspector, not a TOML parser. Accept simple single-line
  # assignments, inline tables/arrays and simple table headers. Unsupported
  # syntax must preserve files instead of being mistaken for no references.
  awk '\''
    function fail() { failed=1; exit 1 }
    function token(type, value) { types[++n]=type; values[n]=value }
    function key(i) {
      return types[i]=="s" || (types[i]=="b" && values[i] ~ /^[A-Za-z0-9_-]+$/)
    }
    BEGIN { single=sprintf("%c", 39) }
    {
      n=0
      for (i=1; i<=length($0); i++) {
        c=substr($0,i,1)
        if (c ~ /[[:space:]]/) continue
        if (c=="#") break
        if (c=="\"" || c==single) {
          if (substr($0,i,3)==c c c) fail()
          quote=c; value=""
          for (j=i+1; j<=length($0); j++) {
            c=substr($0,j,1)
            if (c==quote) break
            if (c=="\\" || c ~ /[[:cntrl:]]/) fail()
            value=value c
          }
          if (j>length($0)) fail()
          token("s", value); i=j
        } else if (c ~ /[A-Za-z0-9_+-]/) {
          value=c
          while (i<length($0) && substr($0,i+1,1) ~ /[A-Za-z0-9_+-]/)
            value=value substr($0,++i,1)
          token("b", value)
        } else if (index("={}[],",c)) {
          token("p",c)
        } else {
          # Includes dots in keys/table paths and escapes in quoted keys.
          fail()
        }
      }
      if (!n) next
      if (types[1]=="p" && values[1]=="[") {
        if (n!=3 || !key(2) || values[2] !~ /^[A-Za-z0-9_-]+$/ || values[3]!="]") fail()
        next
      }
      if (n<3 || !key(1) || types[2]!="p" || values[2]!="=") fail()
      depth=0
      for (i=3; i<=n; i++) {
        if (types[i]!="p") continue
        c=values[i]
        if (c=="{" || c=="[") stack[++depth]=c
        if (c=="}" || c=="]") {
          if (!depth || (c=="}" && stack[depth]!="{") || (c=="]" && stack[depth]!="[")) fail()
          depth--
        }
      }
      if (depth) fail()
      for (i=1; i<=n; i++) {
        if (!key(i) || (values[i]!="sealed" && values[i]!="replay_cache_path") ||
            i+1>n || types[i+1]!="p" || values[i+1]!="=") continue
        if (i+2>n || types[i+2]!="s" || values[i+2]=="") fail()
        references[++count]=values[i] "\t" values[i+2]
      }
    }
    END { if (!failed) for (i=1; i<=count; i++) print references[i] }
  '\'' < <(printf '\''%s\n'\'' "$1")
}

record_other_settings() {
  local settings=$1 config reference kind config_settings references
  OTHER_SETTINGS+=$'\''\n'\''"$settings"
  uses_parallax_resources "$settings" || return 0
  OTHER_INSTANCES=1
  # Inspect the other instance'\''s config as well: it can reference the selected
  # instance'\''s bundle or replay cache even when its own config path differs.
  if ! decode_settings_configs "$settings"; then
    INSPECTION_COMPLETE=0
    echo "kept instance files: could not decode config arguments" >&2
    return 0
  fi
  for config in "${DECODED_CONFIGS[@]}"; do
    if [[ "$config" != /* ]] || ! config="$(run_root readlink -f -- "$config")" ||
      ! config_settings="$(run_root cat -- "$config")"; then
      INSPECTION_COMPLETE=0
      echo "kept instance files: could not inspect config $config" >&2
      return 0
    fi
    OTHER_PATHS+=$'\''\n'\''"$config"
    if ! references="$(decode_config_references "$config_settings")"; then
      INSPECTION_COMPLETE=0
      echo "kept instance files: could not inspect config references in $config" >&2
      return 0
    fi
    while IFS=$'\''\t'\'' read -r kind reference; do
      [[ -n "$kind" ]] || continue
      [[ "$kind" != sealed ]] || reference=${reference%#*}
      [[ "$reference" == /* ]] || reference="$(dirname "$config")/$reference"
      # Resolve relative components and symlinks without executing config
      # contents. Use root privileges for the 0700 shared state directory.
      if ! reference="$(run_root readlink -f -- "$reference")"; then
        INSPECTION_COMPLETE=0
        echo "kept instance files: could not resolve a reference in $config" >&2
        return 0
      fi
      OTHER_PATHS+=$'\''\n'\''"$reference"
    done < <(printf '\''%s\n'\'' "$references")
  done
}

inspect_other_instances() {
  local dir path unit settings loaded
  # Include disabled units, vendor units, symlinked units and service drop-ins;
  # custom --service-name values need not contain "parallax".
  for dir in /etc/systemd/system /run/systemd/system /usr/local/lib/systemd/system /usr/lib/systemd/system /lib/systemd/system; do
    for path in "$dir"/*.service "$dir"/*.service.d/*.conf; do
      [[ -f "$path" ]] || continue
      unit=${path##*/}
      if [[ "$unit" == *.conf ]]; then
        unit=${path%/*}
        unit=${unit##*/}
        unit=${unit%.d}
      fi
      [[ "$unit" != "$SERVICE_UNIT" ]] || continue
      if ! settings="$(run_root cat -- "$path")"; then
        INSPECTION_COMPLETE=0
        echo "kept shared resources: could not inspect $path" >&2
        return
      fi
      record_other_settings "$settings"
    done
  done

  # A loaded/transient unit can outlive its unit file. Inspect its effective
  # settings too, before deleting host keys, binaries or shared host settings.
  if command -v systemctl >/dev/null 2>&1; then
    if ! loaded="$(systemctl list-units --all --type=service --no-legend --plain --no-pager)"; then
      INSPECTION_COMPLETE=0
      echo "kept shared resources: could not inspect loaded services" >&2
      return
    fi
    while read -r unit _; do
      [[ -n "$unit" && "$unit" != "$SERVICE_UNIT" ]] || continue
      if ! settings="$(systemctl show --property=User --property=Description --property=ExecStart --property=WorkingDirectory --property=StateDirectory "$unit")"; then
        INSPECTION_COMPLETE=0
        echo "kept shared resources: could not inspect $unit" >&2
        return
      fi
      record_other_settings "$settings"
    done < <(printf '\''%s\n'\'' "$loaded")
  fi
  if [[ "$OTHER_INSTANCES" == "1" ]]; then
    echo "kept shared resources: another ParallaX service remains"
  fi
}

path_is_referenced() {
  local path=$1 rest=$OTHER_SETTINGS before canonical
  grep -Fxq -- "$path" < <(printf '\''%s\n'\'' "$OTHER_PATHS") && return 0
  if canonical="$(run_root readlink -f -- "$path" 2>/dev/null)"; then
    grep -Fxq -- "$canonical" < <(printf '\''%s\n'\'' "$OTHER_PATHS") && return 0
  fi
  # Match whole path tokens, so /opt/plx-two and config.toml.bak do not retain
  # an unrelated /opt/plx or config.toml. Handle systemd'\''s quoted settings too.
  while [[ "$rest" == *"$path"* ]]; do
    before=${rest%%"$path"*}
    rest=${rest#*"$path"}
    case "${before: -1}" in
      ('\'''\''|[[:space:]]|'\''='\''|'\''"'\''|"'\''"|'\''-'\''|'\''+'\''|'\''!'\''|'\''@'\''|'\'':'\'')
        case "${rest:0:1}" in
          ('\'''\''|[[:space:]]|'\''"'\''|"'\''"|'\'';'\''|'\''#'\''|'\'']'\''|'\''}'\''|'\'','\'') return 0 ;;
        esac
        ;;
    esac
  done
  return 1
}

remove_unreferenced_file() {
  local path=$1
  if path_is_referenced "$path"; then
    echo "kept $path: referenced by another service"
  else
    remove_file "$path"
  fi
}

remove_parca_service() {
  local owned=0
  if [[ -f "$PARCA_SERVICE_PATH" ]] && grep -q '\''/etc/parallax/polarsignals'\'' "$PARCA_SERVICE_PATH"; then
    owned=1
  fi

  if [[ "$owned" == "1" ]]; then
    stop_disable_unit "$PARCA_SERVICE" "$PARCA_SERVICE_PATH"
    remove_file "$PARCA_SERVICE_PATH"
  elif [[ -f "$PARCA_SERVICE_PATH" ]]; then
    echo "kept $PARCA_SERVICE_PATH because it does not look ParallaX-generated"
  else
    echo "missing $PARCA_SERVICE_PATH"
  fi

  remove_file /etc/parallax/polarsignals.env
  remove_file /etc/parallax/polarsignals.token

  if [[ "$REMOVE_PARCA_AGENT" == "1" ]]; then
    if command -v snap >/dev/null 2>&1 && run_root snap list parca-agent >/dev/null 2>&1; then
      run_root snap remove parca-agent || true
    else
      echo "parca-agent snap is not installed"
    fi
  fi
}

remove_bbr_files() {
  [[ "$REMOVE_BBR" == "1" ]] || return 0
  remove_file /etc/modules-load.d/parallax-bbr.conf
  remove_file /etc/sysctl.d/99-parallax-bbr.conf
  # The socket-buffer drop-in is written unconditionally by deploy-vps.sh (even
  # with --no-enable-bbr); clean it up under the same sysctl-persistence toggle.
  remove_file /etc/sysctl.d/99-parallax-netbuf.conf
  if command -v sysctl >/dev/null 2>&1; then
    run_root sysctl --system >/dev/null 2>&1 || true
  fi
}

remove_ufw_rules() {
  [[ "$REMOVE_UFW_RULE" == "1" ]] || return 0
  command -v ufw >/dev/null 2>&1 || return 0

  local status nums n
  status="$(run_root ufw status numbered 2>/dev/null || true)"
  grep -q '\''Status: active'\'' < <(printf '\''%s\n'\'' "$status") || return 0
  nums="$(printf '\''%s\n'\'' "$status" | awk '\''/ParallaX/ { line=$0; sub(/^.*\[/, "", line); sub(/\].*$/, "", line); gsub(/[[:space:]]/, "", line); if (line ~ /^[0-9]+$/) print line }'\'' | sort -rn)"

  if [[ -z "$nums" ]]; then
    echo "no UFW rule with a ParallaX comment found"
    return 0
  fi

  for n in $nums; do
    run_root ufw --force delete "$n" || true
  done
}

remove_remote_files() {
  [[ "$INSPECTION_COMPLETE" == "1" ]] || return 0
  local config_dir replay_cache config_shared=0 suffix
  config_dir="$(dirname "$REMOTE_CONFIG")"
  replay_cache="/var/lib/parallax/replay-$SERVICE_NAME.cache"
  path_is_referenced "$REMOTE_CONFIG" && config_shared=1

  remove_unreferenced_file "$REMOTE_BIN"
  remove_unreferenced_file "$REMOTE_CONFIG"
  if [[ "$config_shared" == "0" ]]; then
    remove_unreferenced_file "$REMOTE_CONFIG.secrets.enc"
    if ! path_is_referenced "$replay_cache"; then
      for suffix in '\'''\'' .0rtt .marker; do
        remove_unreferenced_file "$replay_cache$suffix"
      done
    fi
  fi
  # Legacy bundles/cache and host.key are host-wide resources. Never remove
  # them while another instance can still need them.
  if [[ "$OTHER_INSTANCES" == "0" ]]; then
    remove_file "$config_dir/parallax.secrets.enc"
    remove_file "$config_dir/parallax-replay.cache"
    remove_dir_tree /var/lib/parallax
  fi
  remove_dir_if_empty "$config_dir"
  remove_dir_if_empty /etc/parallax
}

remove_service_user() {
  # Opt-in (--remove-user): every ParallaX instance on this VPS shares the
  # parallax account, so deleting it while another instance'\''s unit still
  # references it would orphan that service'\''s files and break its restart.
  [[ "$REMOVE_USER" == "1" ]] || return 0
  if id -u parallax >/dev/null 2>&1; then
    # Even when opted in, keep the user if any remaining unit still runs as
    # parallax (our own unit file was already removed above).
    local other_units
    other_units="$(grep -rlE '\''^User=parallax$'\'' /etc/systemd/system 2>/dev/null || true)"
    if [[ -n "$other_units" ]]; then
      echo "kept the parallax system user: still referenced by $(printf '\''%s'\'' "$other_units" | tr '\''\n'\'' '\'' '\'')"
      return 0
    fi
    # Best-effort: userdel refuses while processes still run as parallax (for
    # example another ParallaX service instance sharing the user).
    if run_root userdel parallax 2>/dev/null; then
      echo "removed parallax system user"
    else
      echo "warning: could not remove the parallax system user (still in use by another service?)" >&2
    fi
  else
    echo "parallax system user not present"
  fi
}

