}

local_uninstall() {
  [[ "$REMOVE_LOCAL" == "1" ]] || return 0
  if [[ ! -e "$LOCAL_DIR" ]]; then
    log "local config directory not found: $LOCAL_DIR"
    return 0
  fi

  validate_local_dir_for_removal "$LOCAL_DIR"

  if [[ "$DRY_RUN" == "1" ]]; then
    log "dry-run: rm -rf $(shell_quote "$LOCAL_DIR")"
    return 0
  fi

  log "Removing local generated config directory"
  rm -rf -- "$LOCAL_DIR"
}

